// ------------------------------------------------------------ フェーズ
/* **削った量でフェーズが移る。**しきい値は
   `DB/BossExternalBTExcelTable.json` の `HPUnder`（＝残り HP）で、
   移り先は `ChangePhase` / `ForceChangePhase` の引数。
   2026-09-01 の先生の指示「設定で切り替えるより削ったタイミングで
   自動でタイムラインも移行したほうが使いやすい」。

   **各フェーズの行動はそのフェーズの頭からの時刻として描きます。**
   元データの引き金は `UseNormalSkill` の「N 発目」で、どのフェーズも
   3 発目から始まっています。通しの数え方だと 2 つめ以降のフェーズは
   入った瞬間に全部出てしまうので、**フェーズごとに数え直す読み方**を採りました。
   ここはこちらの読みです（ゲーム内での実測ではありません）。 */
/* **HP から決まる表示（フェーズの移り・グロッキー）は、どの振れ方で見るかで変わる。**
   1 発で 2 段ぶん削るとフェーズを飛ばすので、平均で見ているかぎり出ない
   （2026-09-01 の先生の指摘「動画だとフェーズ2をスキップしてフェーズ1から
   フェーズ3に行ってる」）。バーで切り替える */
// 並びは「シナリオ別達成率」の行と同じ。**上の数字も図もここで切り替える**
// （2026-09-01 の先生の指示「上の数字を平均だけじゃなくてシナリオを選べるように」）
// **7 通りは計算用にそのまま残す。**画面から減らしたのは「描く行」と「選べる札」
// だけで、`SCEN` の並びと番号は動かさない（2026-09-03）。
// `verify.py` が `st.scen` に 0〜6 を直接入れて上振れ〜下振れの帯を作っており、
// 3 つに減らしたら 3・4・6 が範囲外になって帯が平均に潰れた
// （c3eN2Cf7QVc の「幅の中」が 90% → 73% に落ちた実測）。**番号は動かさない。**
// 画面に出すのは `ui: true` の 3 つだけ（2026-09-03 の先生の指示
// 「直感的じゃないから平均だけ残して、残りは会心率を自分でバーで調整」）。
// 会心の振れは `st.crit` のバーへ移した
export var SCEN = [{ lab: '下振れ', pf: -1, key: 'min', wide: true, ui: true },
            { lab: '最小', pf: 0, key: 'min' },
            { lab: '0会心平均', pf: 0, key: 'avg0' },
            { lab: '平均', pf: 0, key: 'avg', ui: true },
            { lab: '全会心平均', pf: 0, key: 'avgC' },
            { lab: '最大', pf: 0, key: 'max' },
            { lab: '上振れ', pf: 1, key: 'max', wide: true, ui: true }];
export var SCEN_DEF = 3;
export function scenIx() {
  var i = st.scen == null ? SCEN_DEF : st.scen;
  return (i >= 0 && i < SCEN.length) ? i : SCEN_DEF;
}
export function scen() { return SCEN[scenIx()]; }
